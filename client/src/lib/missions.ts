export function getRangeKey(months: number): string {
  if (months <= 3) return "0-3";
  if (months <= 6) return "4-6";
  if (months <= 12) return "7-12";
  if (months <= 18) return "13-18";
  if (months <= 24) return "19-24";
  return "25-36";
}

/** 날짜 기반으로 오늘의 미션 1개 선택 (매일 자동 로테이션) */
export function getTodayMission(months: number): Mission {
  const pool = missionsByRange[getRangeKey(months)];
  const dayIndex = Math.floor(Date.now() / 86400000);
  return pool[dayIndex % pool.length];
}

